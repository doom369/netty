package io.netty.handler.ssl;

import io.netty.microbench.util.AbstractMicrobenchmark;
import org.openjdk.jmh.annotations.Benchmark;
import org.openjdk.jmh.annotations.BenchmarkMode;
import org.openjdk.jmh.annotations.Mode;
import org.openjdk.jmh.annotations.OutputTimeUnit;
import org.openjdk.jmh.annotations.Scope;
import org.openjdk.jmh.annotations.State;
import org.openjdk.jmh.infra.Blackhole;

import java.util.concurrent.TimeUnit;

/**
 * Measures converting the signature algorithms a typical TLS 1.3 client offers, which is done once per handshake
 * on the server side.
 */
@State(Scope.Benchmark)
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
public class SignatureAlgorithmConverterBenchmark extends AbstractMicrobenchmark {

    private final String[] peerSignatureAlgorithms = {
            "ecdsa_secp256r1_sha256",
            "rsa_pss_rsae_sha256",
            "rsa_pkcs1_sha256",
            "ecdsa_secp384r1_sha384",
            "rsa_pss_rsae_sha384",
            "rsa_pkcs1_sha384",
            "rsa_pss_rsae_sha512",
            "rsa_pkcs1_sha512"
    };

    @Benchmark
    public void toJavaNames(Blackhole blackhole) {
        for (String algorithm : peerSignatureAlgorithms) {
            blackhole.consume(SignatureAlgorithmConverter.toJavaName(algorithm));
        }
    }
}
